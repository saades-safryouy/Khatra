const express=require('express');
const c=require('../controllers/productController');
const {protect}=require('../middleware/auth');
const {uploadProduct}=require('../middleware/upload');
const r=express.Router(); 
r.get('/products',c.publicList); 
r.get('/products/:slug',c.publicBySlug); 
r.get('/admin/products',protect,c.adminList); 
r.post('/admin/products',protect,uploadProduct.array('images',10),c.create); 
r.get('/admin/products/:id',protect,c.adminById); 
r.put('/admin/products/:id',protect,uploadProduct.array('images',10),c.update); 
r.delete('/admin/products/:id',protect,c.remove); module.exports=r;
